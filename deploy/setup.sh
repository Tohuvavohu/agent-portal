#!/usr/bin/env bash
# Write deploy/.env for docker compose: asks for the domain and a login
# provider, generates every secret, and prints the exact OAuth callback URL to
# register. Refuses to overwrite an existing .env — its secrets sign every
# cookie and token, and its database password is baked into the db volume.
set -euo pipefail

cd "$(dirname "$0")"

if [[ -e .env ]]; then
  echo "deploy/.env already exists; edit it directly or move it aside first." >&2
  exit 1
fi

ask() {
  local prompt=$1 default=${2:-} reply
  if [[ -n $default ]]; then
    read -r -p "$prompt [$default]: " reply
    echo "${reply:-$default}"
  else
    while [[ -z ${reply:-} ]]; do read -r -p "$prompt: " reply; done
    echo "$reply"
  fi
}

secret() { openssl rand -base64 "$1" | tr -d '\n/+=' | cut -c1-"$2"; }

# The image for a main-branch commit is tagged major.minor.<commit count>,
# the same version the portal reports, so a checkout knows its own tag.
default_version=""
if git rev-parse --git-dir >/dev/null 2>&1; then
  minor=$(sed -n 's/^version = "\([0-9]*\.[0-9]*\)\..*/\1/p' ../Cargo.toml | head -1)
  default_version="$minor.$(git rev-list --count HEAD)"
fi

domain=$(ask "Public domain for the portal (DNS must point here), e.g. portal.example.com")
acme_email=$(ask "Email for Let's Encrypt certificate notices")
version=$(ask "Portal version to run (image tag)" "$default_version")

echo
echo "Login provider. Create an OAuth app with this callback URL:"
echo "  Google: https://$domain/api/auth/google/callback"
echo "  GitHub: https://$domain/api/auth/github/callback"
provider=$(ask "Provider (google/github)" "github")
case $provider in
  google) prefix=GOOGLE ;;
  github) prefix=GITHUB ;;
  *) echo "Unknown provider: $provider" >&2; exit 1 ;;
esac
client_id=$(ask "$provider OAuth client id")
client_secret=$(ask "$provider OAuth client secret")

echo
echo "Who may sign in? Leave both blank to allow any $provider account."
allowed_emails=$(ask "Allowed emails, comma-separated" "-")
allowed_domain=$(ask "Allowed email domain" "-")

umask 077
{
  echo "# Generated by deploy/setup.sh. Keep this file private and backed up."
  echo "PORTAL_DOMAIN=$domain"
  echo "ACME_EMAIL=$acme_email"
  echo "PORTAL_VERSION=$version"
  echo "POSTGRES_PASSWORD=$(secret 48 40)"
  echo "SESSION_SECRET=$(secret 96 64)"
  echo "${prefix}_CLIENT_ID=$client_id"
  echo "${prefix}_CLIENT_SECRET=$client_secret"
  echo "${prefix}_REDIRECT_URI=https://$domain/api/auth/$provider/callback"
  if [[ $allowed_emails != "-" ]]; then echo "ALLOWED_EMAILS=$allowed_emails"; fi
  if [[ $allowed_domain != "-" ]]; then echo "ALLOWED_EMAIL_DOMAIN=$allowed_domain"; fi
} > .env

echo
echo "Wrote deploy/.env. Start the portal with:"
echo "  cd deploy && docker compose up -d"
echo "then open https://$domain"
